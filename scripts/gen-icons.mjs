// Generates src/core/bitmap/iconNames.generated.ts from the installed `material-symbols` package.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dts = readFileSync(join(root, 'node_modules/material-symbols/index.d.ts'), 'utf8');
const pkg = JSON.parse(readFileSync(join(root, 'node_modules/material-symbols/package.json'), 'utf8'));
const block = dts.slice(dts.indexOf('['), dts.indexOf('];'));
const names = [...block.matchAll(/"([a-z0-9_]+)"/g)].map((m) => m[1]);
const unique = [...new Set(names)].sort();
const out =
  `// AUTO-GENERATED by scripts/gen-icons.mjs from material-symbols@${pkg.version}. Do not edit.\n` +
  `// ${unique.length} icon names (space separated).\n` +
  `export const ICON_NAMES_RAW =\n  ${JSON.stringify(unique.join(' '))};\n`;
writeFileSync(join(root, 'src/core/bitmap/iconNames.generated.ts'), out);
console.log(`wrote ${unique.length} icon names`);
